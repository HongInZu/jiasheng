/** Translates interface copy only. Never apply to user-authored source text. */
export function t(text: string): string {
  if (!isEnglish.value) return text;
  if (english[text] !== undefined) return english[text];
  const lineError = text.match(/^第 (\d+) 行(.+)$/);
  if (lineError) return `Line ${lineError[1]}: check the timestamp format, chronological order, and that the line contains spoken text.`;
  if (text.startsWith('本機 AI 未完成：')) return `Local transcription could not finish. Check the recording and try again. (${text.slice(10)})`;
  if (text.startsWith('故事格式不完整或超過長度限制：')) return 'The story has missing or overlong fields. Shorten the title or headings and try again.';
  if (text.startsWith('故事引用了不存在的對話來源：') || text.startsWith('故事重複引用同一段對話：')) return 'The story contains invalid or duplicate source references. Return to review and recreate it.';
  if (text.endsWith(' 已就緒')) return `${text.slice(0, -4)} ready`;
  const progress = text.match(/^已辨識 (\d+) 個文字片段，仍在核對時間。$/);
  if (progress) return `${progress[1]} text pieces recognized. Aligning timestamps…`;
  return text;
}
export function chooseLanguage(value: Language) {
  language.value = value;
  const url = new URL(window.location.href);
  url.searchParams.set('lang', value === 'en' ? 'en' : 'zh-TW');
  window.history.replaceState(null, '', url);
  try { localStorage.setItem(storageKey, value); } catch { /* The current session still uses the chosen language. */ }
}
