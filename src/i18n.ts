import { computed, ref, watch } from 'vue';

type Language = 'zh-TW' | 'en';
const storageKey = 'jiasheng-language';
function initialLanguage(): Language {
  const requested = new URLSearchParams(window.location.search).get('lang');
  if (requested === 'en') return 'en';
  if (requested === 'zh' || requested === 'zh-TW') return 'zh-TW';
  try { const saved = localStorage.getItem(storageKey); if (saved === 'en' || saved === 'zh-TW') return saved; } catch { /* Private storage may be unavailable. */ }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-TW' : 'en';
}
export const language = ref<Language>(initialLanguage());
